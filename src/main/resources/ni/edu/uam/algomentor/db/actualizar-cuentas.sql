-- Migracion idempotente para instalaciones anteriores al inicio de sesion.
-- Conserva los perfiles e intentos existentes; la cuenta puede reclamarse
-- registrando el usuario con el mismo nombre que el perfil.

CREATE TABLE IF NOT EXISTS cuenta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario         VARCHAR(40)  NOT NULL UNIQUE,
    contrasena_hash VARCHAR(128) NOT NULL,
    perfil_id       BIGINT       NOT NULL UNIQUE
                    REFERENCES perfil (id) ON DELETE CASCADE
);
