-- AlgoMentor: esquema PostgreSQL (8 tablas). Se puede ejecutar varias veces sin borrar datos.

CREATE TABLE IF NOT EXISTS perfil (
                                      id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      nombre         VARCHAR(80)  NOT NULL UNIQUE,
    fecha_creacion TIMESTAMP    NOT NULL DEFAULT now()
    );

CREATE TABLE IF NOT EXISTS algoritmo (
                                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         nombre      VARCHAR(80)  NOT NULL UNIQUE,
    categoria   VARCHAR(20)  NOT NULL CHECK (categoria IN ('ORDENAMIENTO', 'MATEMATICO')),
    complejidad VARCHAR(30),
    descripcion VARCHAR(500)
    );

CREATE TABLE IF NOT EXISTS habilidad (
                                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         nombre      VARCHAR(60)  NOT NULL UNIQUE,
    descripcion VARCHAR(255)
    );

CREATE TABLE IF NOT EXISTS ejercicio (
                                         id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         algoritmo_id   BIGINT      NOT NULL REFERENCES algoritmo (id),
    datos          TEXT        NOT NULL,
    dificultad     INTEGER     NOT NULL CHECK (dificultad BETWEEN 1 AND 5),
    origen         VARCHAR(20) NOT NULL CHECK (origen IN ('ALEATORIO', 'MANUAL', 'PERSONALIZADO')),
    fecha_creacion TIMESTAMP   NOT NULL DEFAULT now()
    );

CREATE TABLE IF NOT EXISTS intento (
                                       id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       perfil_id         BIGINT      NOT NULL REFERENCES perfil (id),
    ejercicio_id      BIGINT      NOT NULL REFERENCES ejercicio (id),
    modo              VARCHAR(20) NOT NULL CHECK (modo IN ('SIMULACION', 'PRACTICA')),
    correcto          BOOLEAN,
    duracion_segundos INTEGER,
    fecha_inicio      TIMESTAMP   NOT NULL DEFAULT now()
    );

CREATE TABLE IF NOT EXISTS paso_intento (
                                            id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            intento_id  BIGINT  NOT NULL REFERENCES intento (id) ON DELETE CASCADE,
    numero_paso INTEGER NOT NULL,
    respuesta   TEXT,
    correcto    BOOLEAN NOT NULL,
    UNIQUE (intento_id, numero_paso)
    );

CREATE TABLE IF NOT EXISTS error_detectado (
                                               id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               paso_intento_id BIGINT      NOT NULL REFERENCES paso_intento (id) ON DELETE CASCADE,
    habilidad_id    BIGINT      NOT NULL REFERENCES habilidad (id),
    tipo_error      VARCHAR(30) NOT NULL CHECK (tipo_error IN ('SIGNO', 'FRACCION', 'ARITMETICO', 'OPERACION_INVALIDA')),
    descripcion     VARCHAR(255)
    );

CREATE TABLE IF NOT EXISTS progreso_habilidad (
                                                  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  perfil_id            BIGINT    NOT NULL REFERENCES perfil (id) ON DELETE CASCADE,
    habilidad_id         BIGINT    NOT NULL REFERENCES habilidad (id),
    aciertos             INTEGER   NOT NULL DEFAULT 0,
    errores              INTEGER   NOT NULL DEFAULT 0,
    ultima_actualizacion TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (perfil_id, habilidad_id)
    );

-- Indices sobre las llaves foraneas
CREATE INDEX IF NOT EXISTS idx_ejercicio_algoritmo   ON ejercicio (algoritmo_id);
CREATE INDEX IF NOT EXISTS idx_intento_perfil        ON intento (perfil_id);
CREATE INDEX IF NOT EXISTS idx_intento_ejercicio     ON intento (ejercicio_id);
CREATE INDEX IF NOT EXISTS idx_error_paso            ON error_detectado (paso_intento_id);
CREATE INDEX IF NOT EXISTS idx_error_habilidad       ON error_detectado (habilidad_id);
CREATE INDEX IF NOT EXISTS idx_progreso_habilidad    ON progreso_habilidad (habilidad_id);

